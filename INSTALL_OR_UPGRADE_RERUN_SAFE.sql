-- Public registration RPC. The event row is locked during seat calculation so two users
-- cannot reserve the same seat capacity at the same time.
create or replace function public.create_registration(p_data jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  es public.event_settings;
  reg_no bigint;
  reg_id text;
  main_name text;
  nationality text;
  main_gender text;
  main_age text;
  mobile text;
  email text;
  extras jsonb;
  fee_breakdown jsonb := '[]'::jsonb;
  total_people integer := 1;
  total_before_discount numeric(12,2) := 0;
  total_amount numeric(12,2) := 0;
  person_fee numeric(12,2) := 0;
  discount_amount numeric(12,2) := 0;
  extra jsonb;
  occupied integer := 0;
  seat_status_value text;
  payment_status_value text := 'Payment Pending';
  registration_status_value text;
  ticket_status_value text := 'Not Valid';
  qr_text text;
  promo_input text;
  promo_valid boolean := false;
  payment_method_value text := 'Cash';
  rating_value smallint;
  feedback_value text;
  rec public.registrations;
begin
  main_name := trim(coalesce(p_data->>'mainParticipant',''));
  nationality := coalesce(p_data->>'nationality','');
  main_gender := coalesce(p_data->>'gender','');
  main_age := coalesce(p_data->>'mainAgeGroup','');
  mobile := regexp_replace(coalesce(p_data->>'mobile',''), '[^0-9]', '', 'g');
  email := trim(coalesce(p_data->>'email',''));
  extras := coalesce(p_data->'participants','[]'::jsonb);
  promo_input := upper(trim(coalesce(p_data->>'promoCode','')));
  rating_value := nullif((p_data->>'rating')::int,0);
  feedback_value := left(trim(coalesce(p_data->>'feedbackComment','')),1000);

  if main_name = '' then raise exception 'Please enter the main participant name.'; end if;
  if nationality not in ('Sri Lankan','Indian') then raise exception 'Please select nationality.'; end if;
  if main_gender not in ('Male','Female') then raise exception 'Please select gender.'; end if;
  if main_age not in ('Infant','Child','Teenager','Adult','Senior') then raise exception 'Please select the main participant age group.'; end if;
  if length(mobile)=9 then mobile:='0'||mobile; end if;
  if mobile !~ '^0[0-9]{9}$' then raise exception 'Mobile number must contain exactly 10 digits and start with 0.'; end if;
  if email !~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' then raise exception 'Please enter a valid email address.'; end if;
  if jsonb_typeof(extras) <> 'array' then raise exception 'Additional participants must be an array.'; end if;
  if rating_value is not null and (rating_value < 1 or rating_value > 5) then raise exception 'Rating must be between 1 and 5 stars.'; end if;

  select * into es from public.event_settings where id=1 for update;
  if not found then raise exception 'Event settings are not available.'; end if;

  if promo_input <> '' then
    if upper(trim(coalesce(es.promo_code,''))) <> '' and promo_input = upper(trim(es.promo_code)) then
      promo_valid := true;
      payment_method_value := 'Promo Code';
    else
      raise exception 'The Promo Code is invalid.';
    end if;
  end if;

  if not promo_valid and coalesce(p_data->>'cashConfirmed','false') <> 'true' then
    raise exception 'Please confirm the cash payment or enter a valid Free Promo Code.';
  end if;

  person_fee := coalesce((es.fees ->> main_age)::numeric,0);
  total_before_discount := person_fee;
  fee_breakdown := fee_breakdown || jsonb_build_object('participant',1,'relation','Main Participant','ageGroup',main_age,'amount',person_fee);

  for extra in select value from jsonb_array_elements(extras) loop
    total_people := total_people + 1;
    if coalesce(extra->>'relation','') = '' or coalesce(extra->>'gender','') not in ('Male','Female') or coalesce(extra->>'ageGroup','') not in ('Infant','Child','Teenager','Adult','Senior') then
      raise exception 'Please complete participant row %.', total_people;
    end if;
    person_fee := coalesce((es.fees ->> (extra->>'ageGroup'))::numeric,0);
    total_before_discount := total_before_discount + person_fee;
    fee_breakdown := fee_breakdown || jsonb_build_object('participant',total_people,'relation',extra->>'relation','gender',extra->>'gender','ageGroup',extra->>'ageGroup','amount',person_fee);
  end loop;

  discount_amount := case when promo_valid then total_before_discount else 0 end;
  total_amount := greatest(total_before_discount - discount_amount,0);

  select coalesce(sum(total_participants),0)::int into occupied
  from public.registrations
  where seat_status in ('Reserved – Payment Pending','Confirmed');

  if occupied + total_people <= es.total_seats then
    if promo_valid then
      seat_status_value:='Confirmed'; payment_status_value:='Paid'; registration_status_value:='Confirmed & Paid'; ticket_status_value:='Valid';
    else
      seat_status_value:='Reserved – Payment Pending'; payment_status_value:='Payment Pending'; registration_status_value:='Reserved – Payment Pending'; ticket_status_value:='Not Valid';
    end if;
  else
    seat_status_value:='Pending';
    if promo_valid then
      payment_status_value:='Paid'; registration_status_value:='Paid – Waiting for Seat'; ticket_status_value:='Not Valid';
    else
      payment_status_value:='Payment Pending'; registration_status_value:='Pending – Waiting for Seat'; ticket_status_value:='Not Valid';
    end if;
  end if;

  reg_no := nextval('public.registration_number_seq');
  reg_id := 'FG26-' || lpad(reg_no::text,6,'0');
  qr_text := json_build_object('registrationId',reg_id,'event',es.event_name)::text;

  insert into public.registrations(
    registration_id, registration_number, main_participant, nationality, gender, main_age_group, mobile, email,
    participants, fee_breakdown, total_participants, entry_fee, total_amount, payment_method, promo_code_used,
    discount_amount, rating, feedback_comment, seat_status, payment_status, registration_status, ticket_status, qr_data
  ) values (
    reg_id, reg_no, main_name, nationality, main_gender, main_age, mobile, email, extras, fee_breakdown, total_people,
    total_before_discount, total_amount, payment_method_value, case when promo_valid then promo_input else '' end,
    discount_amount, rating_value, feedback_value, seat_status_value, payment_status_value, registration_status_value, ticket_status_value, qr_text
  ) returning * into rec;

  if promo_valid and total_amount = 0 then
    insert into public.admin_logs(action,details) values('FREE_PROMO_REGISTRATION',rec.registration_id || ' used the Free Promo Code.');
  end if;

  return jsonb_build_object(
    'registration', jsonb_build_object(
      'registrationId',rec.registration_id,'createdAt',rec.created_at,'mainParticipant',rec.main_participant,'nationality',rec.nationality,'gender',rec.gender,'mainAgeGroup',rec.main_age_group,'mobile',rec.mobile,'email',rec.email,'emailToken',rec.email_token,'participants',rec.participants,'feeBreakdown',rec.fee_breakdown,'totalParticipants',rec.total_participants,'entryFee',rec.entry_fee,'discountAmount',rec.discount_amount,'totalAmount',rec.total_amount,'paymentMethod',rec.payment_method,'promoCodeUsed',rec.promo_code_used,'rating',rec.rating,'feedbackComment',rec.feedback_comment,'seatStatus',rec.seat_status,'paymentStatus',rec.payment_status,'registrationStatus',rec.registration_status,'ticketStatus',rec.ticket_status,'checkedIn',rec.checked_in,'qrData',rec.qr_data
    ),
    'availability',public.get_availability(),'emailEnabled',es.confirmation_email_enabled
  );
end;
$$;
grant execute on function public.create_registration(jsonb) to anon, authenticated;

create or replace function public.find_registration(p_query text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  q text := regexp_replace(trim(coalesce(p_query,'')), '[^0-9A-Za-z_-]', '', 'g');
  rec public.registrations;
begin
  if q ~ '^[0-9]{9}$' then q := '0' || q; end if;
  select * into rec from public.registrations where upper(registration_id)=upper(q) or mobile=q order by created_at desc limit 1;
  if not found then raise exception 'Registration not found.'; end if;
  return jsonb_build_object('registrationId',rec.registration_id,'createdAt',rec.created_at,'mainParticipant',rec.main_participant,'nationality',rec.nationality,'gender',rec.gender,'mainAgeGroup',rec.main_age_group,'mobile',rec.mobile,'participants',rec.participants,'feeBreakdown',rec.fee_breakdown,'totalParticipants',rec.total_participants,'entryFee',rec.entry_fee,'discountAmount',rec.discount_amount,'totalAmount',rec.total_amount,'paymentMethod',rec.payment_method,'promoCodeUsed',rec.promo_code_used,'rating',rec.rating,'feedbackComment',rec.feedback_comment,'seatStatus',rec.seat_status,'paymentStatus',rec.payment_status,'registrationStatus',rec.registration_status,'ticketStatus',rec.ticket_status,'checkedIn',rec.checked_in,'qrData',rec.qr_data);
end;
$$;
grant execute on function public.find_registration(text) to anon, authenticated;

create or replace function public.process_waiting_list_locked()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  es public.event_settings;
  occupied integer := 0;
  rec public.registrations;
begin
  select * into es from public.event_settings where id=1 for update;
  select coalesce(sum(total_participants),0)::int into occupied
  from public.registrations where seat_status in ('Reserved – Payment Pending','Confirmed');

  for rec in
    select * from public.registrations
    where seat_status='Pending'
    order by created_at asc
    for update
  loop
    exit when occupied + rec.total_participants > es.total_seats;
    occupied := occupied + rec.total_participants;
    if rec.payment_status='Paid' then
      update public.registrations
      set seat_status='Confirmed', registration_status='Confirmed & Paid', ticket_status='Valid', updated_at=now()
      where registration_id=rec.registration_id;
    else
      update public.registrations
      set seat_status='Reserved – Payment Pending', registration_status='Reserved – Payment Pending', ticket_status='Not Valid', updated_at=now()
      where registration_id=rec.registration_id;
    end if;
  end loop;
end;
$$;

create or replace function public.sync_registration_income()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'Admin access required.'; end if;
  insert into public.finance_transactions(transaction_date,transaction_type,category,description,amount,reference,notes,created_by,source_type,source_id)
  select r.created_at::date,'Income','Registration Fee','Registration income - '||r.registration_id,r.total_amount,r.registration_id,'Automatically added from paid registration',auth.uid(),'Registration',r.registration_id
  from public.registrations r
  where r.payment_status='Paid' and r.total_amount>0
    and not exists(select 1 from public.finance_transactions t where t.source_type='Registration' and t.source_id=r.registration_id);
  delete from public.finance_transactions t
  where t.source_type='Registration'
    and not exists(select 1 from public.registrations r where r.registration_id=t.source_id and r.payment_status='Paid' and r.total_amount>0);
end;
$$;
grant execute on function public.sync_registration_income() to authenticated;

create or replace function public.admin_dashboard()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  regs jsonb; logs jsonb; es public.event_settings;
begin
  if not public.is_admin() then raise exception 'Admin access required.'; end if;
  perform public.sync_registration_income();
  select * into es from public.event_settings where id=1;
  select coalesce(jsonb_agg(q.x order by q.created_at desc),'[]'::jsonb) into regs
  from (select jsonb_build_object('registrationId',r.registration_id,'createdAt',r.created_at,'mainParticipant',r.main_participant,'nationality',r.nationality,'gender',r.gender,'mainAgeGroup',r.main_age_group,'mobile',r.mobile,'email',r.email,'participants',r.participants,'feeBreakdown',r.fee_breakdown,'totalParticipants',r.total_participants,'entryFee',r.entry_fee,'discountAmount',r.discount_amount,'totalAmount',r.total_amount,'paymentMethod',r.payment_method,'promoCodeUsed',r.promo_code_used,'seatStatus',r.seat_status,'paymentStatus',r.payment_status,'registrationStatus',r.registration_status,'ticketStatus',r.ticket_status,'checkedIn',r.checked_in,'checkedInAt',r.checked_in_at,'qrData',r.qr_data,'emailToken',r.email_token,'rating',r.rating,'feedbackComment',r.feedback_comment) x, r.created_at from public.registrations r) q;
  select coalesce(jsonb_agg(jsonb_build_object('date',l.created_at,'user',coalesce(u.email,'ADMIN'),'action',l.action,'details',l.details) order by l.created_at desc),'[]'::jsonb) into logs from public.admin_logs l left join auth.users u on u.id=l.user_id;
  return jsonb_build_object('settings',jsonb_build_object('eventName',es.event_name,'eventDate',es.event_date,'venue',es.venue,'totalSeats',es.total_seats,'fees',es.fees,'logoUrl',es.logo_url,'promoCode',es.promo_code,'whatsappGroupLink',es.whatsapp_group_link,'confirmationEmailEnabled',es.confirmation_email_enabled,'emailSubject',es.email_subject,'emailBody',es.email_body),'availability',public.get_availability(),'registrations',regs,'adminLog',logs,'finance',public.get_finance_dashboard());
end;
$$;
