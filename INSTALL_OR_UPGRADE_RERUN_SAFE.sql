create or replace function public.get_finance_dashboard()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  opening jsonb;
  budget jsonb;
  tx jsonb;
  opening_amount numeric(14,2) := 0;
  income_total numeric(14,2) := 0;
  expense_total numeric(14,2) := 0;
  budget_total numeric(14,2) := 0;
begin
  if not public.is_admin() then raise exception 'Admin access required.'; end if;

  select jsonb_build_object(
    'amount', ob.amount,
    'asOfDate', ob.as_of_date,
    'notes', ob.notes
  ), ob.amount
  into opening, opening_amount
  from public.finance_opening_balance ob
  where ob.id=1;

  if opening is null then
    opening := jsonb_build_object('amount',0,'asOfDate',null,'notes','');
    opening_amount := 0;
  end if;

  select coalesce(sum(budget_amount) filter (where active),0)
  into budget_total
  from public.finance_budget_items;

  select
    coalesce(sum(amount) filter (where transaction_type='Income'),0),
    coalesce(sum(amount) filter (where transaction_type='Expense'),0)
  into income_total, expense_total
  from public.finance_transactions;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id', b.id,
    'category', b.category,
    'description', b.description,
    'budgetAmount', b.budget_amount,
    'active', b.active,
    'createdAt', b.created_at
  ) order by b.category, b.id), '[]'::jsonb)
  into budget
  from public.finance_budget_items b;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id', t.id,
    'transactionDate', t.transaction_date,
    'transactionType', t.transaction_type,
    'category', t.category,
    'description', t.description,
    'amount', t.amount,
    'reference', t.reference,
    'notes', t.notes,
    'createdAt', t.created_at
  ) order by t.transaction_date desc, t.id desc), '[]'::jsonb)
  into tx
  from public.finance_transactions t;

  return jsonb_build_object(
    'openingBalance', opening,
    'budgetTotal', budget_total,
    'incomeTotal', income_total,
    'expenseTotal', expense_total,
    'closingBalance', opening_amount + income_total - expense_total,
    'budgetRemaining', budget_total - expense_total,
    'budgetItems', budget,
    'transactions', tx
  );
end;
$$;
grant execute on function public.get_finance_dashboard() to authenticated;

