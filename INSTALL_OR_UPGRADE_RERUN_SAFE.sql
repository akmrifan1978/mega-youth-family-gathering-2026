create or replace function public.admin_update_payment_status(p_registration_id text,p_status text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare reg public.registrations; es public.event_settings; occupied integer:=0; new_seat text; new_reg_status text;
begin
  if not public.is_admin() then raise exception 'Admin access required.'; end if;
  if p_status not in ('Payment Pending','Paid','Failed','Expired','Cancelled') then raise exception 'Invalid payment status.'; end if;
  select * into es from public.event_settings where id=1 for update;
  select * into reg from public.registrations where registration_id=upper(p_registration_id) for update;
  if not found then raise exception 'Registration not found.'; end if;
  if p_status='Paid' then
    if reg.seat_status='Pending' then
      perform public.process_waiting_list_locked();
      select * into reg from public.registrations where registration_id=upper(p_registration_id) for update;
      if reg.seat_status='Pending' then update public.registrations set payment_status='Paid',registration_status='Paid – Waiting for Seat',ticket_status='Not Valid',updated_at=now() where registration_id=reg.registration_id;
      else update public.registrations set payment_status='Paid',seat_status='Confirmed',registration_status='Confirmed & Paid',ticket_status='Valid',updated_at=now() where registration_id=reg.registration_id; end if;
    else update public.registrations set payment_status='Paid',seat_status='Confirmed',registration_status='Confirmed & Paid',ticket_status='Valid',updated_at=now() where registration_id=reg.registration_id; end if;
  elsif p_status='Payment Pending' then
    select coalesce(sum(total_participants),0)::int into occupied from public.registrations where seat_status in ('Reserved – Payment Pending','Confirmed') and registration_id<>reg.registration_id;
    if occupied+reg.total_participants<=es.total_seats then new_seat='Reserved – Payment Pending'; new_reg_status='Reserved – Payment Pending'; else new_seat='Pending'; new_reg_status='Pending – Waiting for Seat'; end if;
    update public.registrations set payment_status='Payment Pending',seat_status=new_seat,registration_status=new_reg_status,ticket_status='Not Valid',updated_at=now() where registration_id=reg.registration_id;
  else
