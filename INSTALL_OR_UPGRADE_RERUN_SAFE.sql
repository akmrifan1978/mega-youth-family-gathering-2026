create table if not exists public.event_settings (
  id integer primary key default 1 check (id = 1),
  event_name text not null default 'Mega Youth Family Gathering 2026',
  event_date text not null default 'To be announced',
  venue text not null default 'To be announced',
  total_seats integer not null default 500 check (total_seats >= 0),
  fees jsonb not null default '{"Infant":0,"Child":10,"Teenager":10,"Adult":10,"Senior":10}'::jsonb,
  whatsapp_group_link text not null default '',
  confirmation_email_enabled boolean not null default false,
  email_subject text not null default 'Mega Youth Family Gathering 2026 – Registration Confirmation',
  logo_url text not null default 'logo.svg',
  promo_code text not null default 'FREE2026',
  email_body text not null default 'Assalamu Alaikum,\n\nYour registration for {{EVENT_NAME}} has been received.\n\nRegistration ID: {{REGISTRATION_ID}}\nMain Participant: {{MAIN_PARTICIPANT}}\nTotal Participants: {{TOTAL_PARTICIPANTS}}\nTotal Amount: SAR {{TOTAL_AMOUNT}}\nPayment Status: {{PAYMENT_STATUS}}\nRegistration Status: {{REGISTRATION_STATUS}}\nEvent Date: {{EVENT_DATE}}\nVenue: {{VENUE}}\n\nJazakAllahu Khairan.',
  updated_at timestamptz not null default now()
);

insert into public.event_settings (id) values (1)
on conflict (id) do nothing;

create table if not exists public.admin_users (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role in ('admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.registrations (
  registration_id text primary key,
  registration_number bigint not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  main_participant text not null,
  nationality text not null check (nationality in ('Sri Lankan','Indian')),
  gender text check (gender in ('Male','Female') or gender is null),
  main_age_group text not null check (main_age_group in ('Infant','Child','Teenager','Adult','Senior')),
  mobile text not null,
  email text not null,
  email_token uuid not null default gen_random_uuid(),
  participants jsonb not null default '[]'::jsonb,
  fee_breakdown jsonb not null default '[]'::jsonb,
  total_participants integer not null check (total_participants >= 1),
  entry_fee numeric(12,2) not null default 0,
  total_amount numeric(12,2) not null default 0,
  payment_method text not null default 'Cash' check (payment_method in ('Cash','Promo Code')),
  promo_code_used text not null default '',
  discount_amount numeric(12,2) not null default 0,
  rating smallint check (rating is null or (rating between 1 and 5)),
  feedback_comment text not null default '',
  seat_status text not null,
  payment_status text not null,
  registration_status text not null,
  ticket_status text not null,
  checked_in boolean not null default false,
  checked_in_at timestamptz,
  qr_data text not null
);

create index if not exists registrations_mobile_idx on public.registrations(mobile);
create index if not exists registrations_created_at_idx on public.registrations(created_at desc);
create index if not exists registrations_seat_status_idx on public.registrations(seat_status);
create index if not exists registrations_payment_status_idx on public.registrations(payment_status);

create table if not exists public.admin_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid references auth.users(id) on delete set null,
  action text not null,
  details text not null default ''
);
create index if not exists admin_logs_created_at_idx on public.admin_logs(created_at desc);

-- Security helper
create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_users au
    where au.id = auth.uid()
      and au.role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- First-admin bootstrap: the first authenticated user can become Admin automatically.
-- Once any Admin exists, only an existing Admin can continue using Admin features.
create or replace function public.bootstrap_first_admin()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'You must be signed in.';
  end if;

  -- Prevent two first-users from bootstrapping at the same time.
  perform pg_advisory_xact_lock(84726119);

  if exists (select 1 from public.admin_users where id = auth.uid()) then
    return jsonb_build_object('ok', true, 'role', 'admin', 'created', false);
  end if;

  if exists (select 1 from public.admin_users) then
    raise exception 'An Admin account already exists. Sign in with an existing Admin account.';
  end if;

  insert into public.admin_users(id, role)
  values (auth.uid(), 'admin');

  insert into public.admin_logs(user_id, action, details)
  values (auth.uid(), 'BOOTSTRAP_ADMIN', 'First authenticated user was granted Admin access.');

  return jsonb_build_object('ok', true, 'role', 'admin', 'created', true);
end;
$$;

revoke all on function public.bootstrap_first_admin() from public;
grant execute on function public.bootstrap_first_admin() to authenticated;

-- Availability helper
create or replace function public.get_availability()
returns jsonb
language sql
security definer
set search_path = public
as $$
  with stats as (
    select
      coalesce(sum(total_participants) filter (where seat_status in ('Reserved – Payment Pending','Confirmed')), 0)::int as occupied,
      coalesce(sum(total_participants) filter (where seat_status = 'Confirmed'), 0)::int as confirmed,
      coalesce(sum(total_participants) filter (where seat_status = 'Pending'), 0)::int as waiting
    from public.registrations
  )
  select jsonb_build_object(
    'totalSeats', es.total_seats,
    'reservedSeats', stats.occupied,
    'confirmedSeats', stats.confirmed,
    'waitingParticipants', stats.waiting,
    'availableSeats', greatest(es.total_seats - stats.occupied, 0)
  )
  from public.event_settings es cross join stats
  where es.id = 1;
$$;

grant execute on function public.get_availability() to anon, authenticated;

